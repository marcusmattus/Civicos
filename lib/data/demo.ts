export function demoScenarios(): Record<ScenarioKey, ScenarioConfig> {
  const keys: ScenarioKey[] = ['conservative', 'expected', 'accelerated', 'intervention']
  return keys.reduce(
    (acc, key) => {
      acc[key] = {
        key,
        label: SCENARIO_LABELS[key],
        notes: scenarioNotes[key],
        values: { ...scenarioValues[key] },
      }
      return acc
    },
    {} as Record<ScenarioKey, ScenarioConfig>,
  )
}

